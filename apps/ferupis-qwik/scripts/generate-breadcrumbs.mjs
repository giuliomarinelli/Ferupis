import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROUTES_MODULE_PATH = resolve(APP_ROOT, "src/config/routes.ts");
const OUTPUT_PATH = resolve(APP_ROOT, "src/generated/breadcrumbs.ts");

export const BREADCRUMB_ROOT_ROUTE = "home";

const resolveBreadcrumbRouteKeys = (
  registry,
  routeKey,
  rootRouteKey = BREADCRUMB_ROOT_ROUTE,
) => {
  if (routeKey === rootRouteKey) {
    return undefined;
  }

  const route = registry[routeKey];

  if (!route) {
    throw new Error(`Unknown breadcrumb route "${routeKey}".`);
  }

  if (route.parent == null) {
    return undefined;
  }

  const reversedRouteKeys = [routeKey];
  const visitedRouteKeys = new Set(reversedRouteKeys);
  let parentRouteKey = route.parent;

  while (true) {
    if (visitedRouteKeys.has(parentRouteKey)) {
      throw new Error(
        `Breadcrumb parent cycle detected from route "${routeKey}" at "${parentRouteKey}".`,
      );
    }

    const parentRoute = registry[parentRouteKey];

    if (!parentRoute) {
      throw new Error(
        `Route "${routeKey}" references unknown breadcrumb parent "${parentRouteKey}".`,
      );
    }

    reversedRouteKeys.push(parentRouteKey);
    visitedRouteKeys.add(parentRouteKey);

    if (parentRouteKey === rootRouteKey) {
      return reversedRouteKeys.reverse();
    }

    if (parentRoute.parent == null) {
      return undefined;
    }

    parentRouteKey = parentRoute.parent;
  }
};

const resolveBreadcrumbLabel = (definition, routeKey) => {
  if (typeof definition.label !== "string" || definition.label.trim() === "") {
    throw new Error(`Route "${routeKey}" has no breadcrumb label.`);
  }

  return definition.label;
};

export const buildBreadcrumbManifest = ({
  registry,
  toSiteRoutePath,
  rootRouteKey = BREADCRUMB_ROOT_ROUTE,
}) => {
  if (!registry[rootRouteKey]) {
    throw new Error(`Breadcrumb root route "${rootRouteKey}" does not exist.`);
  }

  const manifest = {};

  for (const routeKey of Object.keys(registry)) {
    const breadcrumbRouteKeys = resolveBreadcrumbRouteKeys(
      registry,
      routeKey,
      rootRouteKey,
    );

    if (!breadcrumbRouteKeys) {
      continue;
    }

    manifest[routeKey] = breadcrumbRouteKeys.map((breadcrumbRouteKey) => {
      const definition = registry[breadcrumbRouteKey];

      return {
        label: resolveBreadcrumbLabel(definition, breadcrumbRouteKey),
        href: toSiteRoutePath(breadcrumbRouteKey),
      };
    });
  }

  return manifest;
};

export const renderBreadcrumbModule = (
  manifest,
) => `// Generated by scripts/generate-breadcrumbs.mjs. Do not edit.
import type { SiteRouteKey } from "../config/routes";

export type BreadcrumbItem = Readonly<{
  label: string;
  href: string;
}>;

export type BreadcrumbManifest = Readonly<
  Partial<Record<SiteRouteKey, readonly BreadcrumbItem[]>>
>;

export const BREADCRUMBS_BY_ROUTE: BreadcrumbManifest = ${JSON.stringify(manifest, null, 2)} as const;
`;

export const generateBreadcrumbs = async ({
  routesModulePath = ROUTES_MODULE_PATH,
  outputPath = OUTPUT_PATH,
} = {}) => {
  const routesModule = await import(pathToFileURL(routesModulePath).href);
  const manifest = buildBreadcrumbManifest({
    registry: routesModule.SITE_ROUTE_REGISTRY,
    toSiteRoutePath: routesModule.toSiteRoutePath,
  });
  const source = renderBreadcrumbModule(manifest);
  const currentSource = await readFile(outputPath, "utf8").catch(
    () => undefined,
  );

  if (currentSource === source) {
    return { changed: false, outputPath };
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");

  return { changed: true, outputPath };
};

const isDirectExecution =
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isDirectExecution) {
  const result = await generateBreadcrumbs();
  const relativeOutputPath = result.outputPath.slice(APP_ROOT.length + 1);
  console.log(
    result.changed
      ? `Generated ${relativeOutputPath}.`
      : `${relativeOutputPath} is up to date.`,
  );
}
